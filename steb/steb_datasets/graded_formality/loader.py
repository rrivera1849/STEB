import csv
from pathlib import Path
from typing import Any, Dict, List


def load_graded_formality(data_dir: str) -> List[Dict[str, Any]]:
    """
    Load the graded formality dataset generated by GPT-5-mini.

    The dataset contains CSV files with columns:
    model, source, input, level1, level2, level3, level4

    Each row represents a text with increasing formality levels:
    - input: original (informal) text
    - level1-level4: progressively more formal versions

    Args:
        data_dir: Path to the dataset directory containing CSV files

    Returns:
        List of records with 'text' (ordered list from informal to formal)
        and 'label' (source type, e.g., "tweet" or "sms") fields.
    """
    data_path = Path(data_dir)

    if not data_path.exists():
        raise ValueError(f"Directory not found: {data_path}")

    records: List[Dict[str, Any]] = []

    # Process all CSV files in the directory
    for csv_file in data_path.glob("*.csv"):
        with csv_file.open("r", encoding="utf-8") as f:
            reader = csv.DictReader(f)

            for row in reader:
                # Extract texts in order from informal to formal
                texts = []
                input_text = row.get("input", "").strip()
                level1 = row.get("level1", "").strip()
                level2 = row.get("level2", "").strip()
                level3 = row.get("level3", "").strip()
                level4 = row.get("level4", "").strip()

                # All levels must be present and non-empty
                if not all([input_text, level1, level2, level3, level4]):
                    continue

                texts = [input_text, level1, level2, level3, level4]

                # Use source as label (e.g., "tweet", "sms"), this could also by formality generally?
                label = row.get("source", "formality").strip()

                records.append({"text": texts, "label": label})

    return records
